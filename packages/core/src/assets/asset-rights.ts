import type { WorkspaceId } from "@money-maker/contracts";
import { type Asset, VERIFIED_CLIP_MODELS } from "./asset.js";
import { modelPolicyFor } from "./model-policy.js";
import { SCENE_CLIP_STAGE } from "./scene-clip-generator.js";
import { STAGE_ARTIFACT_ROLE } from "./stage-cache.js";

export const resolveAssetRights = async (input: {
  workspaceId: WorkspaceId;
  assets: readonly Asset[];
  findAsset: (assetId: string) => Promise<Asset | null>;
}): Promise<readonly Asset[]> => {
  const resolved = new Map<string, Asset>();
  const active = new Set<string>();
  const resolve = async (asset: Asset, depth: number): Promise<Asset> => {
    const cached = resolved.get(asset.id);
    if (cached) return cached;
    if (asset.workspaceId !== input.workspaceId || active.has(asset.id) || depth > 16)
      return { ...asset, commercialUse: null };
    active.add(asset.id);
    if (asset.provenance !== "rendered") {
      active.delete(asset.id);
      resolved.set(asset.id, asset);
      return asset;
    }
    const ids = sourceIds(asset);
    const sources: Asset[] = [];
    let missingSource = false;
    for (const id of ids) {
      const source = await input.findAsset(id);
      if (!source) missingSource = true;
      else sources.push(await resolve(source, depth + 1));
    }
    const rights = sources.some((source) => source.commercialUse === false)
      ? false
      : ids.length > 0 &&
          !missingSource &&
          sources.length === ids.length &&
          sources.every((source) => source.commercialUse === true)
        ? true
        : null;
    const current = { ...asset, commercialUse: rights };
    active.delete(asset.id);
    resolved.set(asset.id, current);
    return current;
  };
  const roots = await Promise.all(input.assets.map((asset) => resolve(asset, 0)));
  for (const asset of roots) resolved.set(asset.id, asset);
  return [...resolved.values()].sort((a, b) => a.id.localeCompare(b.id));
};

const sourceIds = (asset: Asset): readonly string[] => {
  const metadata = asset.metadata ?? {};
  return Array.isArray(metadata.sourceAssetIds)
    ? metadata.sourceAssetIds.filter((value): value is string => typeof value === "string")
    : typeof metadata.sourceAssetId === "string"
      ? [metadata.sourceAssetId]
      : [];
};

export const dependentAssetIds = (assetId: string, assets: readonly Asset[]): readonly string[] => {
  const affected = new Set([assetId]);
  let changed = true;
  while (changed) {
    changed = false;
    for (const asset of assets) {
      if (
        asset.provenance === "rendered" &&
        !affected.has(asset.id) &&
        sourceIds(asset).some((sourceId) => affected.has(sourceId))
      ) {
        affected.add(asset.id);
        changed = true;
      }
    }
  }
  return [...affected].sort();
};

/**
 * A generated scene clip (Agnes) is stored with commercialUse null until the owner records the
 * terms decision (spec 2026-09-30 generative scene clips, G0). The YouTube gate already refuses
 * unverified rights, but other channels publish without an editorial review, so this finds any
 * stored scene clip in the lineage of the given assets that is not verified for commercial use.
 * Other generated assets are untouched.
 */
const isSceneClip = (asset: Asset): boolean =>
  asset.metadata?.["role"] === STAGE_ARTIFACT_ROLE &&
  asset.metadata?.["stage"] === SCENE_CLIP_STAGE;

export const findUnverifiedGeneratedClip = async (input: {
  workspaceId: WorkspaceId;
  assets: readonly Asset[];
  findAsset: (assetId: string) => Promise<Asset | null>;
  verifiedModels?: ReadonlySet<string>;
}): Promise<Asset | undefined> =>
  (await resolveAssetRights(input)).find(
    (asset) =>
      isSceneClip(asset) &&
      !(input.verifiedModels ?? VERIFIED_CLIP_MODELS).has(`agnes:${asset.metadata?.["model"]}`) &&
      !localClipModelAllowed(asset.metadata?.["model"]),
  );

/** A local Wan clip is cleared only while its model is promoted in model policy (owner decision). */
const localClipModelAllowed = (model: unknown): boolean => {
  const policy = typeof model === "string" ? modelPolicyFor(model) : undefined;
  return (
    policy?.capability === "video_generation" &&
    policy.enabled &&
    policy.licensePolicy === "commercial_allowed"
  );
};

/** Any stored generated scene clip in the lineage, verified or not (drives the AI disclosure rule). */
export const findGeneratedClip = async (input: {
  workspaceId: WorkspaceId;
  assets: readonly Asset[];
  findAsset: (assetId: string) => Promise<Asset | null>;
}): Promise<Asset | undefined> => (await resolveAssetRights(input)).find(isSceneClip);

/**
 * Agnes terms of service 6.1 require a clear disclosure to viewers when content is generated by
 * the service. A caption counts when it carries #IA / #AIgenerated or says the content or scenes
 * were generated, made or created by/with IA or inteligência artificial.
 */
const AI_DISCLOSURE =
  /(?:^|\s)#(?:ia|aigenerated|feitocomia|geradoporia)(?=\s|$|[.,!?])|\b(?:gerad[oa]s?|feit[oa]s?|criad[oa]s?)\s+(?:por|com)\s+(?:ia|intelig[eê]ncia\s+artificial)\b/iu;
export const hasAiDisclosure = (caption: string): boolean => AI_DISCLOSURE.test(caption);
