/**
 * Scene bank fill (moved from the worker command for the home worker API, ADR 0012): which
 * plates a niche needs and how to bank generated images through the scene bank.
 */
type ScenePreferences = Readonly<{
  surface?: unknown;
  nicheSetting?: unknown;
  paletteHint?: unknown;
  lighting?: unknown;
}>;

const asRecord = (value: unknown): Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value)
    ? (value as Record<string, unknown>)
    : {};

const scenePreferences = (niche: Niche): ScenePreferences => asRecord(niche.context?.scene);

/** Active pool members younger than 60 days (what the bank counts against poolMin). */
export const activeCount = (assets: readonly Asset[], now: Date): number => {
  const cutoff = now.getTime() - 60 * 86_400_000;
  return assets.filter((asset) => {
    if (asset.state !== "active") return false;
    const createdAt = asset.metadata?.createdAt;
    return typeof createdAt !== "string" || Date.parse(createdAt) >= cutoff;
  }).length;
};

const stringValue = (value: unknown, fallback: string): string =>
  typeof value === "string" && value.trim() ? value.trim() : fallback;

/**
 * v2 slice 24: one wide plate per location that has none pinned. The generate_plates job banks
 * only these (slice 27).
 */
export const plateRequestsFor = (niche: Niche): readonly SceneBankRequest[] => {
  const explainer = niche.kind === "media" ? readExplainerContext(niche) : null;
  const style = explainer?.style;
  if (!explainer || !style) return [];
  const preferences = scenePreferences(niche);
  const palette = asRecord(asRecord(niche.context?.brandKit).palette);
  const paletteHint = stringValue(preferences.paletteHint, stringValue(palette.accent, "neutral"));
  return (explainer.locations ?? [])
    .filter((location) => !location.plate.assetId)
    .map((location) =>
      locationPlateRequest(niche.id, {
        locationId: location.id,
        name: location.name,
        setting: location.proceduralFallback,
        style,
        paletteHint,
      }),
    );
};

/**
 * What to bank for a niche: styled media niches get two painted backgrounds per procedural
 * setting; affiliate niches keep their six product-scene keys. Media niches never get product
 * scenes (they had no use for them).
 */
const requestsFor = (niche: Niche): readonly SceneBankRequest[] => {
  const preferences = scenePreferences(niche);
  const palette = asRecord(asRecord(niche.context?.brandKit).palette);
  const paletteHint = stringValue(preferences.paletteHint, stringValue(palette.accent, "neutral"));
  if (niche.kind === "media") {
    const explainer = readExplainerContext(niche);
    const style = explainer?.style;
    return style
      ? [
          ...BACKGROUNDS.map((setting) =>
            explainerBackgroundRequest(niche.id, { setting, style, paletteHint }),
          ),
          ...plateRequestsFor(niche),
        ]
      : [];
  }
  const surface = ["table", "shelf", "counter", "abstract"].includes(String(preferences.surface))
    ? (preferences.surface as "table" | "shelf" | "counter" | "abstract")
    : "table";
  const lighting = ["top-left", "top-right", "soft-front"].includes(String(preferences.lighting))
    ? (preferences.lighting as "top-left" | "top-right" | "soft-front")
    : "top-left";
  return (["hero", "secondary"] as const).flatMap((role) =>
    (["left", "center", "right"] as const).map((productAnchor) =>
      sceneBankRequest(niche.id, {
        role,
        productAnchor,
        surface,
        lighting,
        nicheSetting: stringValue(preferences.nicheSetting, niche.name),
        paletteHint,
      }),
    ),
  );
};

/** Runs a compositing post-process plan on generated bytes (providers/media/plate-postprocess). */
export type PlatePostProcessor = (
  bytes: Uint8Array,
  plan: ReturnType<typeof platePostProcessPlan>,
) => Promise<
  Readonly<{ bytes: Uint8Array; mimeType: "image/jpeg"; record: Readonly<Record<string, unknown>> }>
>;

/**
 * A media niche with a compositing profile gets its plates post-processed as they are generated
 * (v2 slice 14); the record lands in the asset metadata as `postProcess`.
 */
const generatorFor = (
  deps: SceneBankDeps & Readonly<{ postProcess?: PlatePostProcessor | undefined }>,
  niche: Niche,
): SceneBankDeps["generator"] => {
  const profile = niche.kind === "media" ? readExplainerContext(niche)?.compositing : undefined;
  const base = deps.generator;
  const postProcess = deps.postProcess;
  if (!profile || !base || !postProcess) return base;
  const plan = platePostProcessPlan(profile, scenePaletteFor(niche));
  return {
    generate: async (prompt, size) => {
      const generated = size ? await base.generate(prompt, size) : await base.generate(prompt);
      const out = await postProcess(generated.bytes, plan);
      return { ...generated, bytes: out.bytes, mimeType: out.mimeType, postProcess: out.record };
    },
  };
};

export const fillSceneBank = async (
  deps: SceneBankDeps & Readonly<{ postProcess?: PlatePostProcessor | undefined }>,
  input: Readonly<{
    workspaceId: WorkspaceId;
    niches: readonly Niche[];
    /** Bank only the requests this accepts (the plate job passes the plate keys). */
    only?: (request: SceneBankRequest) => boolean;
    /** A local generator spends no Workers AI neurons, so skip the allowance guard. */
    local?: boolean;
  }>,
): Promise<
  Readonly<{ generated: number; neuronsUsed: number; perKey: Record<string, number> }>
> => {
  const startedAt = deps.now();
  const usageInput = {
    workspaceId: input.workspaceId,
    provider: "cloudflare_workers_ai" as const,
    unit: "neurons" as const,
    since: utcDayStart(startedAt),
  };
  const usageBefore = await deps.usage.sum(usageInput);
  const perKey: Record<string, number> = {};
  let generated = 0;

  for (const niche of input.niches) {
    if (niche.workspaceId !== input.workspaceId || niche.state !== "active") continue;
    const nicheDeps = { ...deps, generator: generatorFor(deps, niche) };
    for (const request of requestsFor(niche).filter(input.only ?? (() => true))) {
      const count = async () =>
        activeCount(
          await deps.assets.listByMetadata({
            workspaceId: input.workspaceId,
            role: request.role,
            key: "sceneKey",
            value: request.key,
          }),
          deps.now(),
        );
      while (true) {
        const before = await count();
        perKey[request.key] = before;
        if (before >= request.poolMin) break;
        const usedToday = await deps.usage.sum(usageInput);
        if (
          deps.budget(usedToday) !== "generate" ||
          (!input.local && usedToday + NEURONS_PER_SCENE > DAILY_NEURON_ALLOWANCE * 0.8)
        )
          break;
        await pickBankedImage(nicheDeps, {
          workspaceId: input.workspaceId,
          request,
          recentSceneIds: [],
        });
        const after = await count();
        perKey[request.key] = after;
        if (after <= before) break;
        generated += after - before;
      }
    }
  }

  return {
    generated,
    neuronsUsed: (await deps.usage.sum(usageInput)) - usageBefore,
    perKey,
  };
};
